const SIZE_PRESETS: Record<DotMatrixSize, { dotSize: number; dotGap: number }> = {
  xs: { dotSize: 2, dotGap: 1 },
  sm: { dotSize: 3, dotGap: 1.5 },
  md: { dotSize: 4.5, dotGap: 2 },
  lg: { dotSize: 6, dotGap: 2.5 },
  xl: { dotSize: 8.5, dotGap: 3 },
  hero: { dotSize: 11, dotGap: 4 },
};

export default function DotMatrixNumber({
  value,
  size = "md",
  dotSize: customDotSize,
  dotGap: customDotGap,
  color = "currentColor",
  inactiveColor,
  showGhostDots = true,
  glow = false,
  className = "",
}: DotMatrixNumberProps) {
  const preset = SIZE_PRESETS[size];
  const dSize = customDotSize ?? preset.dotSize;
  const dGap = customDotGap ?? preset.dotGap;
  const charGap = Math.round(dGap * 2.5);

  const strValue = String(value).toUpperCase();

  // Compute ghost color fallback based on currentColor or transparent black/white
  const ghostColor =
    inactiveColor ?? "color-mix(in srgb, currentColor 10%, transparent)";

  return (
    <span
      className={`inline-flex items-center select-none font-mono tracking-normal ${className}`}
      aria-label={String(value)}
      role="img"
    >
      {strValue.split("").map((char, charIdx) => {
        const matrix = GLYPHS[char];

        // Fallback for unmapped characters: render a simple spacer or character fallback
        if (!matrix) {
          return (
            <span
              key={`fallback-${charIdx}`}
              style={{
                marginLeft: `${charGap}px`,
                fontSize: `${dSize * 7 + dGap * 6}px`,
                lineHeight: 1,
              }}
            >
              {char}
            </span>
          );
        }

        const cols = matrix[0].length;

        return (
          <span
            key={`char-${charIdx}`}
            className="inline-grid shrink-0"
            style={{
              marginLeft: charIdx > 0 ? `${charGap}px` : "0px",
              gridTemplateColumns: `repeat(${cols}, ${dSize}px)`,
              gridTemplateRows: `repeat(7, ${dSize}px)`,
              gap: `${dGap}px`,
            }}
          >
            {matrix.map((row, rowIdx) =>
              row.map((active, colIdx) => {
                const isActive = active === 1;

                if (!isActive && !showGhostDots) {
                  return (
                    <span
                      key={`empty-${rowIdx}-${colIdx}`}
                      style={{
                        width: `${dSize}px`,
                        height: `${dSize}px`,
                      }}
                    />
                  );
                }

                return (
                  <span
                    key={`dot-${rowIdx}-${colIdx}`}
                    className="rounded-full transition-colors duration-150"
                    style={{
                      width: `${dSize}px`,
                      height: `${dSize}px`,
                      backgroundColor: isActive ? color : ghostColor,
                      boxShadow:
                        isActive && glow
                          ? `0 0 ${Math.max(4, dSize * 1.5)}px ${color}`
                          : undefined,
                    }}
                  />
                );
              })
            )}
          </span>
        );
      })}
    </span>
  );
}

